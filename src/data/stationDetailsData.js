function cleanName(rawName = '') {
  return rawName
    .replace(/\(LGM\)|\(LSM\)|\(LBS\)|\(FCR\)|\(TDC\)/gi, '')
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

