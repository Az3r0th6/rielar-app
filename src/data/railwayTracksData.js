// Haversine distance in meters between two [lat, lng] coordinates
export function haversineMeters(p1, p2) {
  if (!p1 || !p2 || p1.length < 2 || p2.length < 2) return 0;
  const R = 6371000;
  const dLat = (p2[0] - p1[0]) * Math.PI / 180;
  const dLng = (p2[1] - p1[1]) * Math.PI / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(p1[0] * Math.PI / 180) * Math.cos(p2[0] * Math.PI / 180) *
    Math.sin(dLng / 2) * Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

function normalizeName(str) {
  return String(str || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '');
}

/**
 * Identifies the exact railway branch key based on lineId, origin, destination and stop names
 */
export function identifyBranchKey(lineId, origName = '', destName = '', extraNames = []) {
  const oNorm = normalizeName(origName);
  const dNorm = normalizeName(destName);
  const allNorms = [oNorm, dNorm, ...extraNames.map(normalizeName)];

  const has = (keyword) => allNorms.some(n => n.includes(keyword) || keyword.includes(n));

  const numericLineId = Number(lineId);

  // Línea Mitre (5)
  if (numericLineId === 5) {
    if (has('tigre') || has('sanisidroc') || has('victoria') || has('belgranoc') || has('sanfernandoc') || has('carupa') || has('virreyes')) return 'mitre-tigre';
    if (has('suarez') || has('ballester') || has('sanmartin') || has('chilavert') || has('miguelete') || has('drago')) return 'mitre-suarez';
    if (has('mitre') || has('coghlan') || has('saavedra') || has('florida') || has('cetrangolo')) return 'mitre-mitre';
    if (has('zarate') || has('campana') || has('escobar') || has('pacheco')) return 'mitre-zarate';
    if (has('capilla') || has('matheu') || has('cardales') || has('savio')) return 'mitre-capilla';
    return 'mitre-tigre';
  }

  // Línea Sarmiento (1)
  if (numericLineId === 1) {
    if (has('mercedes') || has('lujan') || has('rodriguez') || has('alvarez') || has('reja')) return 'sarmiento-mercedes';
    if (has('lobos') || has('heras') || has('marcospaz') || has('ferrari')) return 'sarmiento-lobos';
    return 'sarmiento-moreno';
  }

  // Línea San Martín (31)
  if (numericLineId === 31) {
    return 'sanmartin-cabred';
  }

  // Línea Roca (11)
  if (numericLineId === 11) {
    if (has('laplata') || has('citybell') || has('villaelisa') || has('gonnet') || has('pereyra') || has('ringuelet') || has('tolosa') || has('hudson')) return 'roca-laplata';
    if (has('korn') || has('glew') || has('guernica') || has('burzaco') || has('adrogue') || has('longchamps')) return 'roca-korn';
    if (has('ezeiza') || has('montegrande') || has('llavallol') || has('guillon') || has('jague')) return 'roca-ezeiza';
    if (has('canuelas') || has('spegazzini') || has('suarez') || has('casares') || has('petion')) return 'roca-canuelas';
    if (has('haedo') || has('sanjusto') || has('tablada') || has('catalina') || has('brian')) return 'roca-haedo';
    if (has('gutierrez') || has('santasofia')) return 'roca-gutierrez';
    if (has('policlinico') || has('medicina') || has('periodismo') || has('diagonal73')) return 'roca-universitario';
    if (has('bosques')) {
      if (has('quilmes') || has('berazategui') || has('bernal') || has('wilde') || has('ranelagh')) return 'roca-bosques-q';
      return 'roca-bosques-t';
    }
    return 'roca-korn';
  }

  // Línea Belgrano Sur (21)
  if (numericLineId === 21) {
    if (has('marinos') || has('libertad') || has('castillo') || has('casanova') || has('villegas') || has('bonzi')) return 'belgranosur-marinos';
    if (has('20dejunio')) return 'belgranosur-20junio';
    return 'belgranosur-catan';
  }

  // Tren de la Costa (41)
  if (numericLineId === 41) {
    return 'tdc-delta';
  }

  return null;
}

/**
 * Finds the index of the closest coordinate in track to targetCoord
 */
export function findClosestTrackIndex(track, targetCoord) {
  if (!Array.isArray(track) || track.length === 0 || !targetCoord) return 0;
  let minIdx = 0;
  let minDist = Infinity;
  for (let i = 0; i < track.length; i++) {
    const d = haversineMeters(track[i], targetCoord);
    if (d < minDist) {
      minDist = d;
      minIdx = i;
    }
  }
  return minIdx;
}

/**
 * Returns the sliced high-precision polyline coordinates along the actual railway tracks
 * between origin station and destination station.
 */
export function getTrackCoordinatesForRoute(branchKey, origCoord, destCoord, fallbackCoords = []) {
  const branch = RAILWAY_BRANCHES[branchKey];
  if (!branch || !Array.isArray(branch.track) || branch.track.length < 2) {
    return fallbackCoords;
  }

  const track = branch.track;
  if (!origCoord || !destCoord) {
    return track;
  }

  const startIdx = findClosestTrackIndex(track, origCoord);
  const endIdx = findClosestTrackIndex(track, destCoord);

  if (startIdx === endIdx) {
    return track;
  }

  if (startIdx < endIdx) {
    return track.slice(startIdx, endIdx + 1);
  } else {
    // Reverse direction (inbound towards central terminal)
    return track.slice(endIdx, startIdx + 1).reverse();
  }
}

/**
 * Interpolates the live train position along the actual railway track between
 * prevCoord and nextCoord at progressRatio [0, 1].
 * This guarantees the train stays strictly on the physical rails!
 */
export function interpolatePositionOnTrack(trackCoords, prevCoord, nextCoord, progressRatio = 0.5) {
  const clampedProgress = Math.max(0, Math.min(1, progressRatio));

  if (!Array.isArray(trackCoords) || trackCoords.length < 2 || !prevCoord || !nextCoord) {
    if (prevCoord && nextCoord) {
      return [
        Number((prevCoord[0] + (nextCoord[0] - prevCoord[0]) * clampedProgress).toFixed(5)),
        Number((prevCoord[1] + (nextCoord[1] - prevCoord[1]) * clampedProgress).toFixed(5)),
      ];
    }
    return prevCoord || nextCoord || [-34.5909, -58.375];
  }

  const startIdx = findClosestTrackIndex(trackCoords, prevCoord);
  const endIdx = findClosestTrackIndex(trackCoords, nextCoord);

  const minIdx = Math.min(startIdx, endIdx);
  const maxIdx = Math.max(startIdx, endIdx);
  const isReverse = startIdx > endIdx;

  let segment = trackCoords.slice(minIdx, maxIdx + 1);
  if (isReverse) segment.reverse();

  if (segment.length <= 1) {
    return [
      Number((prevCoord[0] + (nextCoord[0] - prevCoord[0]) * clampedProgress).toFixed(5)),
      Number((prevCoord[1] + (nextCoord[1] - prevCoord[1]) * clampedProgress).toFixed(5)),
    ];
  }

  if (clampedProgress <= 0) return segment[0];
  if (clampedProgress >= 1) return segment[segment.length - 1];

  // Calculate cumulative distances along segment
  const cumDists = [0];
  let totalDist = 0;
  for (let i = 0; i < segment.length - 1; i++) {
    totalDist += haversineMeters(segment[i], segment[i + 1]);
    cumDists.push(totalDist);
  }

  if (totalDist === 0) return segment[0];

  const targetDist = clampedProgress * totalDist;
  for (let i = 0; i < cumDists.length - 1; i++) {
    if (targetDist >= cumDists[i] && targetDist <= cumDists[i + 1]) {
      const segLen = cumDists[i + 1] - cumDists[i];
      const localProg = segLen > 0 ? (targetDist - cumDists[i]) / segLen : 0;
      const p1 = segment[i];
      const p2 = segment[i + 1];
      return [
        Number((p1[0] + (p2[0] - p1[0]) * localProg).toFixed(5)),
        Number((p1[1] + (p2[1] - p1[1]) * localProg).toFixed(5)),
      ];
    }
  }

  return segment[segment.length - 1];
}

/**
 * Returns the complete, ordered master stations list for a branch between origin and destination.
 * Resolves each station name against the master catalog with exact coordinates and IDs.
 */
export function getMasterStopsForBranch(branchKey, origName, destName, lineId, allStationsCatalog = []) {
  const branch = RAILWAY_BRANCHES[branchKey];
  if (!branch || !Array.isArray(branch.stations) || branch.stations.length === 0) {
    return [];
  }

  const stationsList = branch.stations;
  const oNorm = normalizeName(origName);
  const dNorm = normalizeName(destName);

  let origIdx = stationsList.findIndex(n => {
    const sNorm = normalizeName(n);
    return sNorm === oNorm || sNorm.includes(oNorm) || oNorm.includes(sNorm);
  });

  let destIdx = stationsList.findIndex(n => {
    const sNorm = normalizeName(n);
    return sNorm === dNorm || sNorm.includes(dNorm) || dNorm.includes(sNorm);
  });

  if (origIdx === -1) origIdx = 0;
  if (destIdx === -1) destIdx = stationsList.length - 1;

  let slicedNames = [];
  if (origIdx <= destIdx) {
    slicedNames = stationsList.slice(origIdx, destIdx + 1);
  } else {
    slicedNames = stationsList.slice(destIdx, origIdx + 1).reverse();
  }

  const findCatalogStation = (name) => {
    const target = normalizeName(name);
    return allStationsCatalog.find(s => {
      const sNorm = normalizeName(s.name);
      return (sNorm === target || sNorm.includes(target) || target.includes(sNorm)) &&
        (!lineId || s.lineId === lineId);
    }) || allStationsCatalog.find(s => normalizeName(s.name) === target);
  };

  return slicedNames.map((stName, idx) => {
    const geo = findCatalogStation(stName);
    return {
      id: geo?.id || `st-${idx}`,
      name: geo?.name || stName,
      lat: geo?.lat || -34.5909,
      lng: geo?.lng || -58.3750,
      anden: '1',
    };
  });
}
